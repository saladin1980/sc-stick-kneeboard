test("C1 layout: US ANSI full-size, 104 keys, no overlaps, every token the game's defaults use is a key or a known non-key", () => {
  assert.equal(KEYS.KEYS.length, 104);
  assert.equal(new Set(KEYS.KEYS.map((k) => k[0])).size, 104);
  for (let i = 0; i < KEYS.KEYS.length; i++) for (let j = i + 1; j < KEYS.KEYS.length; j++) {
    const a = KEYS.KEYS[i], b = KEYS.KEYS[j];
    assert.ok(!(a[2] < b[2] + b[4] && b[2] < a[2] + a[4] && a[3] < b[3] + b[5] && b[3] < a[3] + a[5]), `${a[0]} overlaps ${b[0]}`);
  }
  const notKeys = /^(mouse\d|mwheel_|maxis_|hmd_)/;
  const unknown = new Set();
  for (const b of R.resolveKeyboard(EMPTY, DATA)) {
    for (const t of [...b.modifiers, b.input]) if (!KEYS.BY_TOKEN.has(t) && !notKeys.test(t)) unknown.add(t);
  }
  assert.deepEqual([...unknown], []);
});

test("C5 oracle: keyboard defaults in the site data == an independent decode of the game's defaultProfile.xml", { skip: fs.existsSync(ORACLE_XML) ? false : "oracle copy missing" }, () => {
  // independent parse: plain regex over the separately decoded XML (not the build script's ElementTree path)
  const xml = fs.readFileSync(ORACLE_XML, "utf8");
  const want = new Set();
  for (const am of xml.matchAll(/<actionmap name="([^"]+)"[\s\S]*?<\/actionmap>/g)) {
    for (const act of am[0].matchAll(/<action name="([^"]+)"([^>]*?)(\/>|>([\s\S]*?)<\/action>)/g)) {
      const attr = /\skeyboard="([^"]*)"/.exec(act[2]);
      if (attr && attr[1].trim()) want.add(`${am[1]}|${act[1]}|${attr[1].trim()}`);
      for (const ch of (act[4] || "").matchAll(/<keyboard\b[^>]*?\sinput="([^"]*)"/g)) if (ch[1].trim()) want.add(`${am[1]}|${act[1]}|${ch[1].trim()}`);
      const kbBlock = /<keyboard\b[^>]*>([\s\S]*?)<\/keyboard>/.exec(act[4] || "");
      if (kbBlock) for (const g of kbBlock[1].matchAll(/\sinput="([^"]*)"/g)) if (g[1].trim()) want.add(`${am[1]}|${act[1]}|${g[1].trim()}`);
    }
  }
  const got = new Set();
  for (const am of DATA.actionmaps) for (const a of am.actions) for (const k of a.keyboard || []) got.add(`${am.name}|${a.name}|${k}`);
  assert.deepEqual([...got].filter((x) => !want.has(x)), [], "in the site data but not in the game's file");
  assert.deepEqual([...want].filter((x) => !got.has(x)), [], "in the game's file but missing from the site data");
  assert.equal(got.size, 523);       // 520 actions; 3 of them carry two keyboard defaults

  // semantic layer (QA C: the raw compare couldn't catch D1): split the oracle's raw strings with the test's
  // OWN rule (key = the non-modifier token; a bare modifier is its own key) and compare key + modifier sets
  // with what the resolver produces for a profile with no rebinds
  const MODS = new Set(["lshift", "rshift", "lctrl", "rctrl", "lalt", "ralt"]);
  const alias = { "]": "rbracket", "[": "lbracket" };
  const mean = (raw) => {
    const t = raw.split("+").map((s) => alias[s.trim()] || s.trim().toLowerCase());
    const keys = t.filter((x) => !MODS.has(x));
    const key = keys.length ? keys[0] : t[t.length - 1];
    return `${key}<${t.filter((x) => x !== key).sort().join("+")}>`;
  };
  const wantSem = new Set([...want].map((s) => { const [am, act, raw] = s.split("|"); return `${am}|${act}|${mean(raw)}`; }));
  const gotSem = new Set(R.resolveKeyboard(EMPTY, DATA).map((b) => `${b.actionmap}|${b.action}|${b.input}<${b.modifiers.slice().sort().join("+")}>`));
  assert.deepEqual([...gotSem].filter((x) => !wantSem.has(x)), [], "resolver meaning differs from the game file");
  assert.deepEqual([...wantSem].filter((x) => !gotSem.has(x)), [], "game file meaning missing from the resolver");
});

test("C2: no rebinds -> exactly the game's keyboard defaults; Sal's rebinds replace them (blank = unbind)", () => {
  const def = R.resolveKeyboard(EMPTY, DATA);
  let n = 0;
  for (const am of DATA.actionmaps) for (const a of am.actions) n += (a.keyboard || []).length;
  assert.equal(def.length, n);
  assert.ok(def.every((b) => b.source === "default"));
  const e = sal();
  assert.equal(e.kbRebinds.length, 130);
  const k = R.resolveKeyboard(e, DATA);
  const rebound = new Set(e.kbRebinds.map((r) => r.actionmap + "|" + r.action));
  assert.ok(!k.some((b) => b.source === "default" && rebound.has(b.actionmap + "|" + b.action)), "a rebound action kept its default");
  for (const r of e.kbRebinds.filter((r) => r.raw)) {
    const [mods, key] = R.splitKeys(r.raw);
    assert.ok(k.some((b) => b.source === "rebind" && b.action === r.action && b.input === key && b.modifiers.join("+") === mods.join("+")), r.raw);
  }
  // evidence for the one-slot rule: never two kb rebinds on one action
  const per = new Map();
  for (const r of e.kbRebinds) per.set(r.actionmap + "|" + r.action, (per.get(r.actionmap + "|" + r.action) || 0) + 1);
  assert.ok([...per.values()].every((v) => v === 1));
});

test("key/modifier split doesn't depend on order (7 game defaults put the modifier last)", () => {
  assert.deepEqual(R.splitKeys("u+lshift"), [["lshift"], "u"]);
  assert.deepEqual(R.splitKeys("f6+lalt"), [["lalt"], "f6"]);
  assert.deepEqual(R.splitKeys("rctrl+rshift+1"), [["rctrl", "rshift"], "1"]);
  assert.deepEqual(R.splitKeys("lalt"), [[], "lalt"]);
  assert.deepEqual(R.splitKeys("lalt+lshift"), [["lalt"], "lshift"]);
  assert.deepEqual(R.splitKeys("K"), [[], "k"]);
  assert.deepEqual(R.splitKeys("]"), [[], "rbracket"]);
  const def = R.resolveKeyboard(EMPTY, DATA);
  const ex = def.find((b) => b.action === "v_emergency_exit");
  assert.deepEqual([ex.modifiers, ex.input], [["lshift"], "u"]);
  // no default lands on a modifier key while also carrying a non-modifier "modifier"
  assert.ok(!def.some((b) => b.modifiers.some((m) => !["lshift", "rshift", "lctrl", "rctrl", "lalt", "ralt"].includes(m))));
});

// QA C D1: parity can't catch a bug both resolvers share, so check the meaning directly
const MODS = new Set(["lshift", "rshift", "lctrl", "rctrl", "lalt", "ralt"]);
test("semantic: a bind lands on a modifier key only as a bare modifier; modifiers are only Shift/Ctrl/Alt", () => {
  const all = [...R.resolveKeyboard(EMPTY, DATA), ...R.resolveKeyboard(sal(), DATA)];
  for (const b of all) {
    if (MODS.has(b.input)) assert.deepEqual(b.modifiers, [], `${b.action}: ${b.modifiers.join("+")}+${b.input}`);
    for (const m of b.modifiers) assert.ok(MODS.has(m), `${b.action}: modifier ${m}`);
  }
});

test("the 7 modifier-last game defaults land on their real key (QA C D1)", () => {
  const want = {
    v_emergency_exit: [["lshift"], "u"],
    v_engineering_assignment_engine_decrease: [["lalt"], "f6"], v_engineering_assignment_engine_min: [["lalt"], "f6"],
    v_engineering_assignment_shields_decrease: [["lalt"], "f7"], v_engineering_assignment_shields_min: [["lalt"], "f7"],
    v_engineering_assignment_weapons_decrease: [["lalt"], "f5"], v_engineering_assignment_weapons_min: [["lalt"], "f5"],
  };
  const def = R.resolveKeyboard(EMPTY, DATA);
  for (const [action, [mods, key]] of Object.entries(want)) {
    const got = def.filter((b) => b.action === action);
    assert.equal(got.length, 1, action);
    assert.deepEqual([got[0].modifiers, got[0].input], [mods, key], action);
  }
});

test("parity: JS keyboard resolver == Python resolve_keyboard on Sal's export", () => {
  const code = ["import sys, json", "sys.path.insert(0, sys.argv[1])", "import resolve_binds as rb",
    "e = rb.parse_export(open(sys.argv[2], encoding='utf-8').read())", "d = json.load(open(sys.argv[3], encoding='utf-8'))",
    "sys.stdout.buffer.write(json.dumps(rb.resolve_keyboard(e, d)).encode('utf-8'))"].join("\n");
  const ctl = fs.readdirSync(path.join(SITE, "data")).find((n) => /^sc-controls-.*\.json$/.test(n));
  const py = JSON.parse(execFileSync("python", ["-I", "-c", code, TOOL, FIXTURE, path.join(SITE, "data", ctl)], { maxBuffer: 32 << 20 }).toString("utf8"));
  const key = (b) => [b.actionmap, b.action, b.input, b.modifiers.join("+"), b.label, b.source, b.activation, b.ui, b.guessed].join("|");
  assert.deepEqual(R.resolveKeyboard(sal(), DATA).map(key).sort(), py.map(key).sort());
});

test("C3/C4 card: every shown bind listed once, 8 px floor, mode colours = stick cards, modifiers marked", () => {
  const binds = R.resolveKeyboard(sal(), DATA).filter((b) => b.ui);
  const r = KK.renderKeyboard({ binds, view: "all", gameVersion: DATA.meta.version, generated: "T" });
  assert.equal(r.stats.binds, binds.length);
  assert.ok(r.stats.fontPxAtDefault >= 8, String(r.stats.fontPxAtDefault));
  assert.ok(!r.svg.includes("foreignObject"));
  assert.equal((r.svg.match(/<g class="key" /g) || []).length, 104);
  const listed = r.listData.blocks.reduce((s, b) => s + b.entries.length, 0);
  assert.equal(listed, binds.length, "list holds every shown bind exactly once");
  assert.equal(r.links.length, r.stats.overflowRows);
  for (const l of r.links) assert.ok(r.listData.blocks.some((b) => b.input === l.input));
  for (const m of r.listData.legend) assert.equal(m.colour, M.MODES.find((x) => x.name === m.name).colour);
  assert.match(r.svg, /R\^ /);                                   // a modifier combo is marked on its key
  assert.match(r.svg, /L\^\/R\^ = Left\/Right Ctrl/);
  const off = r.listData.blocks.find((b) => b.input === "off-picture");
  assert.ok(off && off.entries.every((e) => /^(mouse|mwheel|maxis|hmd)/i.test(e.text)), "only non-keys are off the keyboard");
  // a single-mode view only has that mode
  const f = KK.renderKeyboard({ binds, view: "flight", gameVersion: "", generated: "T" });
  assert.deepEqual(f.stats.modes, ["flight"]);
});

