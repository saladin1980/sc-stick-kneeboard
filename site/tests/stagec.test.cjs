test("keyboard opens on Flight, with a hint; 'Print every mode' prints one keyboard page per mode (Master 2026-11-11)", () => {
  const app = fs.readFileSync(path.join(SITE, "js", "app.js"), "utf8");
  assert.match(app, /const KB_DEFAULT_VIEW = "flight";/);
  assert.match(app, /if \(c\.kind === "kb" && !c\.view\) c\.view = modes\.some\(\(m\) => m\.id === KB_DEFAULT_VIEW\)/);
  assert.match(app, /"Pick a mode: the full keyboard has too many binds to show at once\."/);
  assert.match(app, /text: "Print every mode"/);
  // the set = one page per mode that has binds; each page is the card only
  const binds = R.resolveKeyboard(sal(), DATA).filter((b) => b.ui);
  const modes = M.MODES.filter((m) => binds.some((b) => M.modeOf(b.actionmap).id === m.id));
  for (const m of modes) {
    const r = KK.renderKeyboard({ binds, view: m.id, gameVersion: "", generated: "T" });
    assert.deepEqual(r.stats.modes, [m.id]);
    assert.ok(!r.pageSvg.includes("every bind, in full"));
  }
  const css = fs.readFileSync(path.join(SITE, "css", "kneeboard.css"), "utf8");
  const print = css.slice(css.indexOf("@media print"));
  assert.match(print, /body\.print-kb-modes > \*:not\(\.kb-print-set\) \{ display: none !important; \}/);
  assert.match(print, /\.kb-print-page \+ \.kb-print-page \{ break-before: page/);
  assert.match(css.slice(0, css.indexOf("@media print")), /\.kb-print-set \{ display: none; \}/);   // never on screen
  // why Flight is the default: it overflows on far fewer keys than All modes (Sal's export: 6 vs 33)
  const f = KK.renderKeyboard({ binds, view: "flight", gameVersion: "", generated: "T" });
  const all = KK.renderKeyboard({ binds, view: "all", gameVersion: "", generated: "T" });
  assert.ok(f.stats.overflowRows * 4 <= all.stats.overflowRows, `${f.stats.overflowRows} vs ${all.stats.overflowRows}`);
});
