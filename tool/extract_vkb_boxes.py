"""Read the VKB fillable PDFs fetched by fetch_vkb_templates.py and produce what the site needs.

    .venv\\Scripts\\python -B extract_vkb_boxes.py

Writes:
  site\\data\\vkb-templates.json   per template: page size (pt), every form field's rect (pt), the
                                   field map (field -> SC input), title, side, grip, PDF SHA-256
  site\\art\\vkb\\<KEY>.js           the page rendered at 3x (2376x1836), empty boxes, as a JS data URI (the
                                   page loads art only this way). Ships: the VKB template art is free to use
                                   per VKB (Sal, 2026-11-11: "imgs are free use so they came FROM vkb directly").
  Templates\\vkb\\render\\<KEY>.jpg  the same render as JPG: a build intermediate, never shipped.
Reads only Templates\\vkb\\ (our downloads). Needs PyMuPDF (build-time only, never shipped).
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import pymupdf

HERE = Path(__file__).resolve().parent
VKB = HERE.parent / "Templates" / "vkb"
SITE = HERE.parent / "site"
SCALE = 3


def main() -> int:
    manifest = json.loads((VKB / "templates.json").read_text(encoding="utf-8"))
    fmap = json.loads((HERE / "vkb_fieldmap.json").read_text(encoding="utf-8"))
    art = SITE / "art" / "vkb"
    art.mkdir(parents=True, exist_ok=True)
    out = {"_about": "Generated by tool/extract_vkb_boxes.py from the VKB Gladiator fillable PDFs "
                     "(UntoldForce v1.0). Rects are PDF points, origin top-left.",
           "fieldmap": fmap["fields"], "templates": {}}
    for key, meta in manifest.items():
        pdf = VKB / meta["file"]
        doc = pymupdf.open(pdf)
        page = doc[0]
        fields = {}
        for w in page.widgets():
            name = w.field_name
            if name in fmap["skip"]:
                continue
            group, part = (name.rsplit("_", 1) if name.endswith(("_1", "_2")) else (name, "2"))
            slot = fields.setdefault(group, {})
            slot["num" if part == "1" else "text"] = [round(v, 2) for v in w.rect]
        title = next((b[4].strip() for b in page.get_text("blocks") if b[4].strip().startswith("VKB Gladiator")), key)
        pix = page.get_pixmap(matrix=pymupdf.Matrix(SCALE, SCALE), annots=False)
        render = VKB / "render"
        render.mkdir(exist_ok=True)
        img = render / f"{key}.jpg"
        pix.save(img, jpg_quality=88)
        out["templates"][key] = {
            "title": title, "side": meta["side"], "grip": meta["grip"], "sal_default": meta.get("sal", False),
            "page": [page.rect.width, page.rect.height], "image": f"art/vkb/{key}.js",
            "image_px": [pix.width, pix.height], "fields": dict(sorted(fields.items())),
            # provenance (the download URL) stays in Templates\vkb\templates.json; the site ships no URLs
            "pdf_sha256": hashlib.sha256(pdf.read_bytes()).hexdigest(), "source_file": meta["file"],
        }
        print(f"{key}: {len(fields)} field groups, art {img.name} {pix.width}x{pix.height}")
    (SITE / "data" / "vkb-templates.json").write_text(json.dumps(out, ensure_ascii=False, indent=1),
                                                      encoding="utf-8", newline="\n")
    from sitejs import write_art_js, write_js       # the page can't fetch: data + art ship as JS
    write_js(out, SITE / "data" / "vkb-templates.js", "KBMAP_VKB", "from vkb-templates.json by extract_vkb_boxes.py")
    for key in out["templates"]:
        write_art_js(VKB / "render" / f"{key}.jpg", art / f"{key}.js", key)
    return 0


if __name__ == "__main__":
    sys.exit(main())
